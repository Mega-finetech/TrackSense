import type { Href } from 'expo-router';
import { Bell, CalendarDays, ChartNoAxesColumn, CheckSquare, FileText, Flame, Target, Timer, type LucideIcon } from 'lucide-react-native';
import type { Notification } from '../../types';

export type AlertVisual = {
  Icon: LucideIcon;
  color: string;
  background: string;
};

const visuals: Record<string, AlertVisual> = {
  task_due: { Icon: CheckSquare, color: '#2563EB', background: '#DBEAFE' },
  exam_soon: { Icon: CalendarDays, color: '#D97706', background: '#FEF3C7' },
  streak_risk: { Icon: Flame, color: '#DC2626', background: '#FEE2E2' },
  goal_deadline: { Icon: Target, color: '#2D6A4F', background: '#DCFCE7' },
  assignment_overdue: { Icon: FileText, color: '#7C3AED', background: '#EDE9FE' },
  focus_sessions: { Icon: Timer, color: '#0891B2', background: '#CFFAFE' },
  weekly_review: { Icon: ChartNoAxesColumn, color: '#4F46E5', background: '#E0E7FF' },
};

const fallback: AlertVisual = { Icon: Bell, color: '#6B7280', background: '#F3F4F6' };

export function alertVisual(type: string): AlertVisual {
  return visuals[type] ?? fallback;
}

/**
 * Alert types are generated by the backend. Each one lands on the screen where
 * the user can act on it without leaving the alert card stack.
 */
export function alertTarget(type: string): Href {
  switch (type) {
    case 'task_due':
      return '/tasks';
    case 'exam_soon':
      return '/exams';
    case 'assignment_overdue':
      return '/assignments';
    case 'goal_deadline':
      return '/goals';
    case 'streak_risk':
      return '/spiritual';
    case 'focus_sessions':
      return '/focus';
    case 'weekly_review':
      return '/analytics';
    default:
      return '/';
  }
}

export type AlertDestination = {
  targetScreen: Href;
  params?: Record<string, string>;
};

/**
 * Resolves an alert into the route and query params used by Profile's
 * deep-link handler. `related_id` is optional on server alerts, so the params
 * object is only attached when there is something to carry across.
 */
export function alertDestination(alert: Pick<Notification, 'type' | 'related_id'>): AlertDestination {
  const targetScreen = alertTarget(alert.type);
  if (!alert.related_id) return { targetScreen };
  return { targetScreen, params: { relatedId: alert.related_id } };
}
